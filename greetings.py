def pick_greeting(today, greetings=GREETINGS):
    """Поздравление на дату `today` — детерминированно по дню года.

    Один и тот же день -> одно и то же поздравление; за 100 дней подряд
    тексты не повторяются.
    """
    index = (today.timetuple().tm_yday - 1) % len(greetings)
    return greetings[index]
